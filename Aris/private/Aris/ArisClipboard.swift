//
//  ArisClipboard.swift
//  Aris
//
//  Clipboard history, after Maccy (github.com/p0deje/Maccy, MIT): each copy keeps all its pasteboard data (text,
//  rich text, images, files), copying the same thing again moves it to the top and counts it, pinned items stay on
//  top, search is exact then fuzzy, and concealed/transient copies and password apps are never kept. Pure: the
//  watching, pasting and saving are in ArisClipboardModel.
//

import Foundation

enum ArisClipboard {
    struct Content: Codable, Equatable {
        let type: String
        let data: Data
    }

    struct Item: Codable, Equatable, Identifiable {
        let id: UUID
        var contents: [Content]
        /// What the list shows: the text, the file paths, or "" for an image.
        var title: String
        /// The app in front when it was copied (its name).
        var app: String?
        var appBundle: String?
        var firstCopied: Date
        var lastCopied: Date
        var copies = 1
        var pinned = false

        var isImage: Bool { contents.contains { ArisClipboard.imageTypes.contains($0.type) } }
        var size: Int { contents.reduce(0) { $0 + $1.data.count } }
    }

    static let limit = 200
    /// Bigger copies are kept for this session but not saved to disk.
    static let savedItemLimit = 2_000_000
    /// Copies bigger than this aren't kept at all.
    static let itemLimit = 20_000_000

    static let stringType = "public.utf8-plain-text"
    static let fileURLType = "public.file-url"
    static let imageTypes: Set = ["public.png", "public.tiff", "public.jpeg", "public.heic"]
    /// Marks a copy made by the notch itself, so it isn't recorded again.
    static let ownType = "com.lumenjsn.aris.clipboard"

    /// Never kept (nspasteboard.org markers, and Maccy's default list of apps' private types).
    private static let ignoredTypes: Set = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "com.typeit4me.clipping", "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type", "net.antelle.keeweb", ownType,
    ]
    private static let passwordApps: Set = ["com.1password.1password", "com.agilebits.onepassword7", "com.apple.keychainaccess",
                                            "com.apple.passwords", "com.bitwarden.desktop"]
    /// Huge or ever-changing data no one pastes back (web archives, link previews, Chromium/Office internals).
    private static let droppedTypes: Set = ["com.apple.webarchive", "Apple Web Archive pasteboard type",
                                            "com.apple.linkpresentation.metadata", "com.apple.WebKit.custom-pasteboard-data",
                                            "org.chromium.internal.source-rfh-token"]

    /// Whether a copy with these pasteboard types, made in front of this app (bundle id), may be kept.
    static func keeps(types: [String], app bundleID: String?) -> Bool {
        guard !types.contains(where: ignoredTypes.contains) else { return false }
        return !(bundleID.map { passwordApps.contains($0.lowercased()) } ?? false)
    }

    /// Whether a pasteboard type is worth keeping and pasting back.
    static func keepsType(_ type: String) -> Bool {
        !droppedTypes.contains(type) && !type.hasPrefix("dyn.") && !type.hasPrefix("com.microsoft.ole.source.")
    }

    /// The list title for these contents: file paths, else the text (cut to 1,000), else "".
    static func title(of contents: [Content]) -> String {
        let files = contents.filter { $0.type == fileURLType }
            .compactMap { URL(dataRepresentation: $0.data, relativeTo: nil)?.path }
        if !files.isEmpty { return files.joined(separator: "\n") }
        let text = contents.first { $0.type == stringType }.map { String(decoding: $0.data, as: UTF8.self) } ?? ""
        return String(text.trimmingCharacters(in: .whitespacesAndNewlines).prefix(1_000))
    }

    /// A new copy: an older item it covers (same data for every type the old one had) gives way to it, keeping
    /// its pin, first date and count; unpinned items beyond the limit drop off the end.
    static func adding(_ item: Item, to items: [Item]) -> [Item] {
        var new = item
        var rest: [Item] = []
        for old in items {
            if old.contents.allSatisfy({ new.contents.contains($0) }) {
                new.copies = old.copies + 1
                new.firstCopied = old.firstCopied
                new.pinned = new.pinned || old.pinned
            } else {
                rest.append(old)
            }
        }
        return trimmed(sorted([new] + rest))
    }

    /// Pinned first, then newest first.
    static func sorted(_ items: [Item]) -> [Item] {
        items.filter(\.pinned) + items.filter { !$0.pinned }.sorted { $0.lastCopied > $1.lastCopied }
    }

    static func trimmed(_ items: [Item]) -> [Item] {
        var unpinned = 0
        return items.filter { item in
            if item.pinned { return true }
            unpinned += 1
            return unpinned <= limit
        }
    }

    /// A copy that looks like a password, key or token (one long run of mixed characters, no spaces): kept for the
    /// session but never written to disk.
    static func looksSecret(_ item: Item) -> Bool {
        let text = item.title
        guard (16...512).contains(text.count), !text.contains(where: \.isWhitespace), !text.hasPrefix("/"),
              !text.lowercased().hasPrefix("http") else { return false }
        let hasDigit = text.contains(where: \.isNumber), hasLetter = text.contains(where: \.isLetter)
        let counts = Dictionary(text.map { ($0, 1) }, uniquingKeysWith: +)
        let entropy = counts.values.reduce(0.0) { total, count in
            let share = Double(count) / Double(text.count)
            return total - share * log2(share)
        }
        return hasDigit && hasLetter && entropy >= 3.5
    }

    /// Plain text (and files) only: "paste without formatting".
    static func plain(_ contents: [Content]) -> [Content] {
        let text = contents.filter { $0.type == stringType || $0.type == fileURLType }
        return text.isEmpty ? contents : text
    }

    /// Like Maccy's mixed search: case-insensitive matches first; with none, letters in order (fuzzy), tightest first.
    static func search(_ query: String, in items: [Item]) -> [Item] {
        let wanted = query.trimmingCharacters(in: .whitespaces)
        guard !wanted.isEmpty else { return items }
        let exact = items.filter { $0.title.range(of: wanted, options: [.caseInsensitive, .diacriticInsensitive]) != nil }
        if !exact.isEmpty { return exact }
        return items.compactMap { item in fuzzySpan(wanted.lowercased(), in: item.title.lowercased()).map { (item, $0) } }
            .sorted { $0.1 < $1.1 }
            .map(\.0)
    }

    /// How spread out the query's letters are in the text (smaller is better); nil when they aren't all there in order.
    static func fuzzySpan(_ query: String, in text: String) -> Int? {
        let letters = query.filter { !$0.isWhitespace }
        guard !letters.isEmpty else { return nil }
        var position = text.startIndex, start: String.Index?
        for letter in letters {
            guard let found = text[position...].firstIndex(of: letter) else { return nil }
            if start == nil { start = found }
            position = text.index(after: found)
        }
        return text.distance(from: start!, to: position)
    }
}
